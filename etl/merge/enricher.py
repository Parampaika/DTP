DTP_TO_ECON = {v: k for k, v in FINAL_MUNI_MAPPING.items()}


class EconomicEnricher:
    def __init__(self, config: dict, logger: logging.Logger):
        self.config = config
        self.logger = logger
        # Умное чтение конфига модели (severe или fatal)
        self.target_mode = self.config.get("modeling", {}).get("target_mode", "binary_severe")

    def _assign_econ_muni(self, dtp_id: str) -> str:
        dtp_id = str(dtp_id)
        if dtp_id in DTP_TO_ECON:
            return DTP_TO_ECON[dtp_id]
        if dtp_id.startswith('москва__'):
            return 'Город Москва'
        if dtp_id.startswith('санктпетербург__'):
            return 'Город Санкт-Петербург'
        return None

    def build_datasets(self, df_dtp: pd.DataFrame, df_econ: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
        self.logger.info("--- 1. Географический маппинг ---")
        
        df_dtp['econ_join_key'] = df_dtp['region_id'].apply(self._assign_econ_muni)
        df_dtp_geo = df_dtp.dropna(subset=['econ_join_key']).copy()
        
        self.logger.info(f"Сматчено аварий с Экономикой: {len(df_dtp_geo)} из {len(df_dtp)}")

        self.logger.info("--- 2. Временной фильтр (только общие годы) ---")
        common_years = set(df_dtp['year']).intersection(set(df_econ['year']))
        df_dtp_ready = df_dtp_geo[df_dtp_geo['year'].isin(common_years)].copy()
        df_econ_ready = df_econ[df_econ['year'].isin(common_years)].copy()
        
        self.logger.info(f"Общие годы: {sorted(list(common_years))}. Строк ДТП в работу: {len(df_dtp_ready)}")

        # =========================================================
        # 3. Сборка MICRO (Для ML модели)
        # =========================================================
        self.logger.info("--- 3. Сборка MICRO-датасета ---")
        econ_features_to_keep = [
            'municipality', 'year', 'Population', 'GAP', 'Avg_Salary', 
            'Employment', 'Street_Length', 'Land_Area', 'RTA_dead', 'RTA_serious', 'RTA_minor'
        ]
        df_econ_micro = df_econ_ready[[c for c in econ_features_to_keep if c in df_econ_ready.columns]]

        df_micro = pd.merge(
            df_dtp_ready,
            df_econ_micro,
            left_on=['econ_join_key', 'year'],
            right_on=['municipality', 'year'],
            how='inner'
        )
        df_micro.drop(columns=['econ_join_key', 'municipality'], inplace=True, errors='ignore')

        # =========================================================
        # 4. Сборка MACRO (Для аналитики и регрессий)
        # =========================================================
        self.logger.info("--- 4. Сборка MACRO-датасета ---")
        self.logger.info(f"Режим расчета макро-таргета: {self.target_mode}")
        
        if self.target_mode == "binary_fatal":
            severe_cond = lambda x: (x == 2).sum()
        else:
            severe_cond = lambda x: (x >= 1).sum()

        dtp_agg = df_dtp_ready.groupby(['econ_join_key', 'year']).agg(
            total_dtp=('target', 'count'),
            severe_dtp=('target', severe_cond)
        ).reset_index()

        df_macro = df_econ.merge(
            dtp_agg,
            left_on=['municipality', 'year'],
            right_on=['econ_join_key', 'year'],
            how='left'
        )

        df_macro['dtp_severe_share'] = df_macro['severe_dtp'] / df_macro['total_dtp']
        
        pop_in_10k = df_macro['Population'] / 10
        df_macro['dtp_per_10k'] = df_macro['total_dtp'] / pop_in_10k
        df_macro['severe_per_10k'] = df_macro['severe_dtp'] / pop_in_10k

        df_macro.drop(columns=['econ_join_key'], inplace=True, errors='ignore')

        self.logger.info(f"Успех! Размер MICRO: {df_micro.shape} | Размер MACRO: {df_macro.shape}")
        return df_micro, df_macro